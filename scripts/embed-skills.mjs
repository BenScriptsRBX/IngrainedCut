// embed-skills.mjs — bakes every bundled skill (skills/<name>/**) into electron/skillsBundle.mjs, so the app, the
// helper and their installers carry the skills inside their own code instead of as loose files.
//   node scripts/embed-skills.mjs           write electron/skillsBundle.mjs
//   node scripts/embed-skills.mjs --check   exit 1 if it is out of date with skills/
// The pack scripts and `npm run build` run it; tests/skills.test.mjs checks it matches skills/ byte for byte.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'skills');
const OUT = path.join(ROOT, 'electron', 'skillsBundle.mjs');

export function skillsSource() {
  const skills = {};
  if (!fs.existsSync(SRC)) return skills;
  for (const e of fs.readdirSync(SRC, { withFileTypes: true }).filter((x) => x.isDirectory()).sort((a, b) => a.name.localeCompare(b.name))) {
    const dir = path.join(SRC, e.name);
    if (!fs.existsSync(path.join(dir, 'SKILL.md'))) continue;
    const files = {};
    const walk = (d, rel) => {
      for (const f of fs.readdirSync(d, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
        const r = rel ? `${rel}/${f.name}` : f.name;
        if (f.isDirectory()) walk(path.join(d, f.name), r);
        else if (f.isFile() && !f.name.endsWith('.bak')) files[r] = fs.readFileSync(path.join(d, f.name)).toString('base64');
      }
    };
    walk(dir, '');
    skills[e.name] = files;
  }
  return skills;
}

export function bundleText() {
  return `// Generated by scripts/embed-skills.mjs from skills/ — do not edit by hand; run \`node scripts/embed-skills.mjs\`.
// The bundled skills, file by file (base64, so every byte is kept), baked into the program.
export const SKILLS = ${JSON.stringify(skillsSource(), null, 1)};
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const want = bundleText();
  const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  if (process.argv.includes('--check')) {
    if (have !== want) {
      console.error('electron/skillsBundle.mjs is out of date: run node scripts/embed-skills.mjs');
      process.exit(1);
    }
    console.log('electron/skillsBundle.mjs is up to date');
  } else {
    if (have !== want) fs.writeFileSync(OUT, want);
    console.log(`[embed-skills] ${Object.keys(skillsSource()).join(', ') || 'no skills'} → electron/skillsBundle.mjs`);
  }
}
